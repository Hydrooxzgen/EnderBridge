function getLang() {
  var l = localStorage.getItem(LANG_KEY) || "zh";
  return I18N[l] ? l : "zh";
}

function setLang(lang) {
  if (!I18N[lang]) return;
  localStorage.setItem(LANG_KEY, lang);
  applyI18n();
  // applyI18n 只替换 data-i18n / data-i18n-ph / data-i18n-title 静态区;
  // 各页面 JS 渲染的动态区(如 permissions 页的用户表格/角色列表)需重渲染刷新
  try {
    if (typeof _refreshPermLang === "function") _refreshPermLang();
  } catch (e) {}
  // 通用钩子:页面可定义 window._onLangChange 或监听 langchange 事件
  try {
    if (typeof window !== "undefined" && typeof window._onLangChange === "function") window._onLangChange();
  } catch (e) {}
  try {
    if (typeof window !== "undefined" && typeof window.dispatchEvent === "function") window.dispatchEvent(new Event("langchange"));
  } catch (e) {}
}

function t(key) {
  var lang = getLang();
  var dict = I18N[lang] || I18N.zh;
  if (dict[key] !== undefined) return dict[key];
  if (I18N.zh[key] !== undefined) return I18N.zh[key];
  return key;
}

/** 扫描 data-i18n / data-i18n-ph 并替换文本 */
function applyI18n() {
  var lang = getLang();
  document.documentElement.setAttribute("lang", lang === "zh" ? "zh-CN" : "en");
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    el.innerHTML = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  // 语言切换按钮自身文案
  document.querySelectorAll(".lang-toggle .lang-label").forEach(function (el) {
    el.textContent = t("common.lang");
  });
  // 主题按钮文案需跟随语言刷新(主题状态不变)
  if (typeof updateThemeIcon === "function") {
    var cur = document.documentElement.getAttribute("data-theme") || "dark";
    updateThemeIcon(cur);
  }
}

function toggleLang() {
  setLang(getLang() === "zh" ? "en" : "zh");
}

function initLang() {
  applyI18n();
  document.querySelectorAll(".lang-toggle").forEach(function (btn) {
    btn.addEventListener("click", toggleLang);
  });
}

